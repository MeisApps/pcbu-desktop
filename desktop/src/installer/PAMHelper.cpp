void PAMHelper::MigrateConfigEntry(const std::string &configName, const std::string &oldEntry, const std::string &newEntry) {
  auto configPath = PAM_CONFIG_DIR / configName;
  if(!ConfigExists(configPath))
    return;

  auto fileStr = ReadConfig(configPath);
  auto migrated = false;
  if(fileStr.contains(PAM_CONFIG_GEN_ENTRY_OLD)) {
    fileStr = StringUtils::Replace(fileStr, std::string(PAM_CONFIG_GEN_ENTRY_OLD), std::string(PAM_CONFIG_GEN_ENTRY));
    migrated = true;
  }
  if(fileStr.contains(oldEntry)) {
    m_Logger(fmt::format("Migrating PAM entry in {}...", configPath.string()));
    fileStr = StringUtils::Replace(fileStr, oldEntry, newEntry);
    migrated = true;
  }
  if(!migrated)
    return;
  m_PendingChanges[configPath] = fileStr;
}
