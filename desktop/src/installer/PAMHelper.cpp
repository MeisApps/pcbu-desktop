void PAMHelper::CommitWithTerminal(const std::map<std::filesystem::path, std::optional<std::string>> &changes) {
  auto id = StringUtils::RandomString(16, false);
  if(id.empty())
    throw std::runtime_error(I18n::Get("error_mac_pam_update", I18n::Get("product_name")));
  auto stagingDir = AppSettings::GetBaseDir() / "pam-staging" / id;
  auto applyFile = stagingDir / "apply.sh";
  auto commandFile = stagingDir / "update.command";
  auto statusFile = PlatformHelper::GetTempDir() / fmt::format("pcbu-pam-{}.status", id);
  auto cleanup = [&]() {
    Shell::RunCommand(fmt::format("rm -rf {}", StringUtils::ShellQuote(stagingDir.string())));
    LocalShell::Remove(statusFile);
  };

  m_Logger("Updating PAM configuration...");
  if(!Shell::CreateDir(stagingDir))
    throw std::runtime_error(I18n::Get("error_file_write", stagingDir.string()));

  std::string applyScript = "#!/bin/bash\nset -e\n";
  std::string fileList{};
  auto fileIdx = 0;
  for(const auto &[path, data] : changes) {
    auto target = StringUtils::ShellQuote(path.string());
    if(data.has_value()) {
      auto stagedFile = stagingDir / fmt::format("file{}", fileIdx++);
      if(!Shell::WriteBytes(stagedFile, {data->begin(), data->end()})) {
        cleanup();
        throw std::runtime_error(I18n::Get("error_file_write", stagedFile.string()));
      }
      applyScript += fmt::format("/usr/bin/install -S -m 0644 -o root -g wheel {} {}\n", StringUtils::ShellQuote(stagedFile.string()), target);
    } else {
      applyScript += fmt::format("/bin/rm -f {}\n", target);
    }
    fileList += fmt::format("printf '  %s\\n' {}\n", target);
  }

  auto commandScript = fmt::format(R"SH(#!/bin/bash
STATUS_FILE={0}
trap 'echo failed > "$STATUS_FILE"; exit 1' HUP INT TERM
clear
printf '%s\n\n' {1}
{2}
printf '\n%s\n\n' {3}
if /usr/bin/sudo /bin/bash {4}; then
  echo ok > "$STATUS_FILE"
  printf '\n%s\n' {5}
  TTY_PATH="$(tty)"
  (/usr/bin/osascript -e 'on run argv' -e 'tell application "Terminal"' -e 'repeat with w in windows' \
    -e 'if tty of selected tab of w is item 1 of argv then' -e 'close w' -e 'exit repeat' -e 'end if' \
    -e 'end repeat' -e 'if (count of windows) is 0 then quit' -e 'end tell' -e 'end run' "$TTY_PATH" >/dev/null 2>&1 &)
  exit 0
fi
echo failed > "$STATUS_FILE"
printf '\n%s\n' {6}
exit 1
)SH",
                                   StringUtils::ShellQuote(statusFile.string()), StringUtils::ShellQuote(I18n::Get("mac_pam_terminal_intro", I18n::Get("product_name"))), fileList,
                                   StringUtils::ShellQuote(I18n::Get("mac_pam_terminal_instructions")), StringUtils::ShellQuote(applyFile.string()),
                                   StringUtils::ShellQuote(I18n::Get("mac_pam_terminal_success")), StringUtils::ShellQuote(I18n::Get("mac_pam_terminal_failed", I18n::Get("product_name"))));

  auto stagingDirStr = StringUtils::ShellQuote(stagingDir.string());
  if(!Shell::WriteBytes(applyFile, {applyScript.begin(), applyScript.end()}) ||
     !Shell::WriteBytes(commandFile, {commandScript.begin(), commandScript.end()}) ||
     Shell::RunCommand(fmt::format("chown -R root:wheel {0} && chmod 755 {1} {0} && chmod 644 {0}/* && chmod 755 {2}", stagingDirStr,
                                   StringUtils::ShellQuote(stagingDir.parent_path().string()), StringUtils::ShellQuote(commandFile.string())))
             .exitCode != 0) {
    cleanup();
    throw std::runtime_error(I18n::Get("error_file_write", stagingDir.string()));
  }

  if(LocalShell::RunUserCommand(fmt::format("open -a Terminal {}", StringUtils::ShellQuote(commandFile.string()))).exitCode != 0) {
    cleanup();
    throw std::runtime_error(I18n::Get("error_mac_pam_update", I18n::Get("product_name")));
  }
  m_Logger(I18n::Get("mac_pam_terminal_waiting"));

  std::string status{};
  auto deadline = std::chrono::steady_clock::now() + TERMINAL_TIMEOUT;
  while(status.empty() && std::chrono::steady_clock::now() < deadline) {
    std::this_thread::sleep_for(TERMINAL_POLL_INTERVAL);
    if(!std::filesystem::exists(statusFile))
      continue;
    auto statusData = LocalShell::ReadBytes(statusFile);
    status = StringUtils::Trim(std::string(statusData.begin(), statusData.end()));
  }
  cleanup();
  if(status != "ok") {
    spdlog::error("PAM update in Terminal did not succeed. (Status={})", status.empty() ? "timeout" : status);
    throw std::runtime_error(I18n::Get("error_mac_pam_update", I18n::Get("product_name")));
  }

  for(const auto &[path, data] : changes) {
    auto exists = std::filesystem::exists(path);
    auto isApplied = data.has_value() ? exists && ReadConfig(path) == data.value() : !exists;
    if(!isApplied) {
      spdlog::error("PAM file was not updated. (Path={})", path.string());
      throw std::runtime_error(I18n::Get("error_mac_pam_update", I18n::Get("product_name")));
    }
  }
}
